/**
 * ⚠️ CATÁLOGO DE DEMOSTRACIÓN
 * ---------------------------------------------------------------------------
 * Ninguna de estas publicaciones es real. Todas tienen `isDemo: true`, la
 * referencia empieza por "MF-DEMO-" y la interfaz muestra una etiqueta DEMO.
 * Existen para que el marketplace se pueda recorrer y probar antes de tener
 * inventario real.
 *
 * Las marcas y modelos citados son equipos que existen en el mercado; lo que
 * NO existe es esta publicación concreta, su propietario, su precio ni su
 * disponibilidad. Por eso los precios llevan etiqueta DEMO y varias
 * publicaciones usan "Consultar precio", que será lo habitual al inicio.
 *
 * `rating: null` y `reviewCount: 0` en todas: no se inventa reputación.
 *
 * Las imágenes son ilustraciones vectoriales generadas (`isPlaceholder: true`),
 * no fotografías. Las fotos reales las sube el propietario al publicar.
 */

const NOW = "2026-05-20T10:00:00.000Z";

/** Construye las 3 ilustraciones de marcador de posición de una categoría. */
function placeholderImages(icon: MachineIconName, label: string) {
  return (["a", "b", "c"] as const).map((v) => ({
    url: `/placeholders/${icon}-${v}.svg`,
    alt: `Ilustración referencial de ${label.toLowerCase()} — publicación de demostración, sin fotografías reales`,
    isPlaceholder: true,
  }));
}

type DemoInput = Omit<
  Machine,
  | "images"
  | "rating"
  | "reviewCount"
  | "isDemo"
  | "status"
  | "createdAt"
  | "updatedAt"
  | "currency"
  | "ownerPlan"
  | "ownerIsFounder"
  | "featuredUntil"
> & { currency?: Machine["currency"]; createdAt?: string };

function demo(input: DemoInput): Machine {
  const category = getCategoryById(input.categoryId);
  return {
    ...input,
    currency: input.currency ?? "PEN",
    images: placeholderImages(category?.icon ?? "other", category?.singular ?? "maquinaria"),
    status: "published",
    rating: null,
    reviewCount: 0,
    createdAt: input.createdAt ?? NOW,
    updatedAt: NOW,
    // DEMO: sin plan pagado, sin fundador y sin destacado (no se simula visibilidad comprada).
    ownerPlan: "start",
    ownerIsFounder: false,
    featuredUntil: null,
    isDemo: true,
  };
}

